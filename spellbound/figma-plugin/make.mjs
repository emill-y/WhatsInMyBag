// Bundles assets.json and src/plugin.js into code.js, the file Figma runs.
import { readFileSync, writeFileSync } from 'node:fs';
const here = new URL('.', import.meta.url);
const assets = readFileSync(new URL('assets.json', here), 'utf8');
const plugin = readFileSync(new URL('src/plugin.js', here), 'utf8');
writeFileSync(new URL('code.js', here), `// Generated by make.mjs from src/plugin.js and assets.json. Edit those, then run: node make.mjs\nconst ASSETS = ${assets};\n${plugin}`);
console.log('code.js written');
